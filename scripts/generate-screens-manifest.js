// Regenerates data/screensManifest.ts by scanning data/screens/*/part-*.json.
// Run after any precompute pipeline run that adds/removes screens files:
//   node scripts/generate-screens-manifest.js

const fs = require('fs');
const path = require('path');

const SCREENS_DIR = path.join(__dirname, '..', 'data', 'screens');
const OUT_FILE = path.join(__dirname, '..', 'data', 'screensManifest.ts');
const PART_RE = /^part-(\d+)\.json$/;

function collectEntries() {
  const entries = [];
  if (!fs.existsSync(SCREENS_DIR)) return entries;

  const recordingIds = fs.readdirSync(SCREENS_DIR, { withFileTypes: true })
    .filter(d => d.isDirectory())
    .map(d => d.name)
    .sort();

  for (const recordingId of recordingIds) {
    const dir = path.join(SCREENS_DIR, recordingId);
    const files = fs.readdirSync(dir);
    const partIndices = files
      .map(f => f.match(PART_RE))
      .filter(Boolean)
      .map(m => parseInt(m[1], 10))
      .sort((a, b) => a - b);
    for (const partIndex of partIndices) {
      entries.push({ recordingId, partIndex });
    }
  }
  return entries;
}

function render(entries) {
  const byRecording = new Map();
  for (const { recordingId, partIndex } of entries) {
    if (!byRecording.has(recordingId)) byRecording.set(recordingId, []);
    byRecording.get(recordingId).push(partIndex);
  }

  const recordingBlocks = [...byRecording.entries()].map(([recordingId, partIndices]) => {
    const partLines = partIndices
      .map(i => `    ${i}: () => require('./screens/${recordingId}/part-${i}.json'),`)
      .join('\n');
    return `  '${recordingId}': {\n${partLines}\n  },`;
  }).join('\n');

  return `// AUTO-GENERATED by scripts/generate-screens-manifest.js — do not hand-edit.
// Regenerate after adding/removing files under data/screens/:
//   node scripts/generate-screens-manifest.js

export interface Screen {
  index: number;
  start: number;
  end: number;
  lines: string[];
}
export interface ScreensFile {
  audio: string;
  screens: Screen[];
}

// recordingId -> partIndex -> lazy loader (each require() is a literal string
// so Metro can statically include it in the bundle graph; wrapping it in an
// arrow function defers actually loading/parsing the JSON until first use).
export const SCREENS_MANIFEST: Record<string, Record<number, () => ScreensFile>> = {
${recordingBlocks}
};

export function hasScreens(recordingId: string, partIndex: number): boolean {
  return !!SCREENS_MANIFEST[recordingId]?.[partIndex];
}

export function loadScreens(recordingId: string, partIndex: number): ScreensFile | null {
  const loader = SCREENS_MANIFEST[recordingId]?.[partIndex];
  return loader ? loader() : null;
}
`;
}

const entries = collectEntries();
fs.writeFileSync(OUT_FILE, render(entries), 'utf-8');
console.log(`Wrote ${OUT_FILE} (${entries.length} part(s) across ${new Set(entries.map(e => e.recordingId)).size} lecture(s))`);

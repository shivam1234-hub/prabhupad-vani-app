// Regenerates data/talkManifest.ts from data/talk/*.json (written by
// scripts/talk_segments.py). Literal require() strings so Metro bundles them;
// wrapped in arrows so each file is only parsed when its lecture plays.
//   node scripts/generate-talk-manifest.js
const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, '..', 'data', 'talk');
const OUT = path.join(__dirname, '..', 'data', 'talkManifest.ts');

const ids = fs.existsSync(DIR)
  ? fs.readdirSync(DIR).filter(f => f.endsWith('.json')).map(f => f.slice(0, -5)).sort()
  : [];

const lines = ids.map(id => `  ${JSON.stringify(id)}: () => require('./talk/${id}.json'),`);
fs.writeFileSync(OUT, `// AUTO-GENERATED by scripts/generate-talk-manifest.js — do not edit.
// "Prabhupāda only" keep-ranges per lecture: { parts: { [partIndex]: [[start, end], ...] }, talkSec, totalSec }.
/* eslint-disable @typescript-eslint/no-require-imports */
export interface TalkData {
  parts: Record<string, [number, number][]>;
  talkSec: number;
  totalSec: number;
}

export const TALK: Record<string, () => TalkData> = {
${lines.join('\n')}
};
`);
console.log(`talkManifest: ${ids.length} lectures`);
